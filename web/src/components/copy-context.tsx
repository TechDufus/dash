import { ClipboardCopy } from "lucide-react";
import { type JSX, useRef, useState } from "react";
import { toast } from "sonner";
import { api, errorMessage } from "@/api/client";
import { useMe } from "@/api/queries";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { Textarea } from "@/components/ui/textarea";
import { ClipboardUnavailableError, copyFromTextarea, copyText } from "@/lib/clipboard";
import { usePluginsState } from "@/plugins/state";

/** The bundle parts every copy asks for; `logs` is added for a principal with the logs scope. */
const PARTS = "events,related,attention,series";

/** The toast's reason for a bundle without log lines, by the summary line's sentence. */
const NO_LOGS_REASONS: Record<string, string> = {
  // The button asks for logs only with the logs scope, so a bundle without them lacks the scope.
  "logs were not requested": "needs the logs scope",
  "the logs scope is required": "needs the logs scope",
};

/**
 * The toast of a copied bundle, from the summary line dash writes ahead of the untrusted block:
 * how many log lines it carries, why it carries none, or nothing about logs for an object that
 * never has any (logsNote not_applicable).
 */
export function copiedMessage(name: string, markdown: string): string {
  const head = markdown.split("\n").find((l) => l.startsWith("Generated by dash at ")) ?? "";
  if (head.endsWith(" This object has no logs.")) return `Copied context for ${name}`;
  const reason = / No log lines: ([^.]+)\.$/.exec(head)?.[1];
  if (reason) return `Copied context for ${name} (no logs: ${NO_LOGS_REASONS[reason] ?? reason})`;
  const lines = Number(/ (\d+) log lines\./.exec(head)?.[1] ?? 0);
  return `Copied context for ${name} (${lines} ${lines === 1 ? "line" : "lines"} of logs)`;
}

interface CopyContextButtonProps {
  /** The object's plugin:Kind/id reference. */
  contextRef: string;
  /** What the toast calls the object. */
  name: string;
  size?: "xs" | "sm";
  className?: string;
}

/**
 * "Copy context for AI" (design Q.1): the object's context bundle as Markdown on the clipboard.
 * The click makes one request, GET /api/v1/context; the logs scope comes from the cached /me.
 * Where the async clipboard is missing or refused, a dialog shows the Markdown for a copy in a
 * click of its own. Nothing renders unless the ref's plugin implements Objects (`objects` on its
 * row of the cached plugin list): any other ref would answer 404 "unknown object".
 */
export function CopyContextButton({
  contextRef,
  name,
  size = "sm",
  className,
}: CopyContextButtonProps): JSX.Element | null {
  const me = useMe();
  const { byId } = usePluginsState();
  const [pending, setPending] = useState(false);
  const [manual, setManual] = useState<string | null>(null);
  const logs = me.data?.scopes?.includes("logs") === true;
  const plugin = contextRef.slice(0, Math.max(0, contextRef.indexOf(":")));

  const copy = () => {
    setPending(true);
    // No await before copyText: the clipboard write must start inside the click.
    const markdown = api.text("/api/v1/context", {
      ref: contextRef,
      format: "markdown",
      include: logs ? `${PARTS},logs` : PARTS,
    });
    copyText(markdown)
      .then(
        (text) => toast.success(copiedMessage(name, text)),
        (err: unknown) =>
          err instanceof ClipboardUnavailableError
            ? setManual(err.text)
            : toast.error(`Copying context failed: ${errorMessage(err)}`),
      )
      .finally(() => setPending(false));
  };

  if (byId.get(plugin)?.objects !== true) return null;
  return (
    <>
      <Button
        type="button"
        variant="outline"
        size={size}
        className={className}
        disabled={pending}
        onClick={copy}
      >
        <ClipboardCopy aria-hidden="true" />
        Copy context for AI
      </Button>
      <ManualCopyDialog name={name} text={manual} onClose={() => setManual(null)} />
    </>
  );
}

/**
 * The bundle's Markdown in a read-only, preselected textarea, for a browser whose async clipboard
 * is missing or refused the write after the fetch. "Copy" runs execCommand inside its own click,
 * the user gesture the browser asks for; ctrl+c works on the selection too.
 */
function ManualCopyDialog({
  name,
  text,
  onClose,
}: {
  name: string;
  text: string | null;
  onClose: () => void;
}): JSX.Element {
  const area = useRef<HTMLTextAreaElement>(null);

  const copy = () => {
    if (!area.current || text === null) return;
    if (copyFromTextarea(area.current)) {
      toast.success(copiedMessage(name, text));
      onClose();
    } else {
      toast.error("Copying failed: the text is selected, press Ctrl+C or ⌘C");
    }
  };

  return (
    <Dialog open={text !== null} onOpenChange={(open) => !open && onClose()}>
      <DialogContent
        className="sm:max-w-2xl"
        onOpenAutoFocus={(e) => {
          e.preventDefault();
          area.current?.focus();
          area.current?.select();
        }}
      >
        <DialogHeader>
          <DialogTitle>Copy context for {name}</DialogTitle>
          <DialogDescription>
            The browser didn't let dash write to the clipboard on this page (a page served over
            plain http, for one). The Markdown is selected below: copy it with the button.
          </DialogDescription>
        </DialogHeader>
        <Textarea
          ref={area}
          readOnly
          aria-label={`Context for ${name}`}
          value={text ?? ""}
          className="field-sizing-fixed max-h-[50vh] min-h-40 font-mono text-xs"
          rows={12}
          onFocus={(e) => e.currentTarget.select()}
        />
        <DialogFooter>
          <Button type="button" variant="outline" onClick={onClose}>
            Close
          </Button>
          <Button type="button" onClick={copy}>
            <ClipboardCopy aria-hidden="true" />
            Copy
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
