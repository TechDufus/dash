// EnvVar describes one setting and the variable that sets it, for `dash config env`.
type EnvVar struct {
	Path        string // dotted path in the config file
	Name        string // generated environment variable
	Type        string // "string", or what the JSON value holds
	Secret      bool   // the value is a credential
	Restart     bool   // a change needs a restart
	Description string // the doc tag of the field
	Default     string // the built-in value, as written in the environment; "" when there is none
}

// EnvVars lists every setting in schema order.
func EnvVars() []EnvVar {
	tree := DefaultTree()
	treeType := reflect.TypeFor[Tree]()
	out := make([]EnvVar, 0, len(schema.leaves))
	for _, l := range schema.leaves {
		t := envType(l.typ)
		doc := treeType.FieldByIndex(l.index).Tag.Get("doc")
		out = append(out, EnvVar{l.path, l.env, t, l.secret, l.restart, doc, defaultText(l.field(&tree))})
	}
	return out
}

// envType is how the generated tables name the type of a setting.
func envType(typ reflect.Type) string {
	elem := typ
	if elem.Kind() == reflect.Pointer {
		elem = elem.Elem()
	}
	switch {
	case elem == durationType:
		return "duration (e.g. 30s)"
	case elem.Kind() == reflect.Bool:
		return "boolean"
	case elem.Kind() == reflect.Int:
		return "integer"
	case elem.Kind() == reflect.Slice && elem.Elem().Kind() == reflect.String:
		return "list of strings (JSON)"
	case elem.Kind() == reflect.Slice && elem.Elem().Kind() == reflect.Int:
		return "list of integers (JSON)"
	case elem.Kind() == reflect.Map:
		return "object (JSON)"
	case elem.Kind() == reflect.Slice:
		return "list of objects (JSON)"
	}
	return "string"
}

// defaultText is a default as it would be written in the environment.
func defaultText(v reflect.Value) string {
	for v.Kind() == reflect.Pointer {
		if v.IsNil() {
			return ""
		}
		v = v.Elem()
	}
	switch {
	case v.Type() == secretType || v.IsZero():
		return ""
	case v.Type() == durationType:
		return pluginconf.Duration(v.Int()).String()
	case v.Kind() == reflect.String:
		return v.String()
	case v.Kind() == reflect.Int:
		return strconv.FormatInt(v.Int(), 10)
	}
	b, err := json.Marshal(v.Interface())
	if err != nil {
		return ""
	}
	return string(b)
}

// WriteEnvTable prints EnvVars as an aligned table, plus the rules that apply to every name.
func WriteEnvTable(w io.Writer) error {
	tw := tabwriter.NewWriter(w, 0, 0, 2, ' ', 0)
	fmt.Fprintln(tw, "PATH\tENV\tTYPE\tSECRET\tRESTART")
	for _, v := range EnvVars() {
		fmt.Fprintf(tw, "%s\t%s\t%s\t%s\t%s\n", v.Path, v.Name, v.Type, yesNo(v.Secret), yesNo(v.Restart))
	}
	if err := tw.Flush(); err != nil {
		return err
	}
	_, err := io.WriteString(w, `
Every name also takes a _FILE form (DASH_NAME_FILE=/path) that reads the value from a file; set
one of the two. The environment overrides the config file. Lists and objects are JSON. KUBECONFIG
is also honoured for plugins.kubernetes.kubeconfig; it has no _FILE form and the generated name
wins over it.

A change to a plugins.<id> section applies live for prometheus, alertmanager, gatus,
victorialogs, proxmox, hardware, kubernetes, grafana, headlamp and launcher, except for a setting
marked in the RESTART column: that plugin restarts, and so do the plugins that use or require it
(a prometheus change restarts proxmox, hardware and kubernetes; a gatus change restarts hardware
and kubernetes; a proxmox change restarts hardware; a kubernetes change restarts proxmox;
a grafana change restarts alertmanager). A change to flux, or to any section that is not a
plugin's, needs a restart. A rotated secret (a changed file: reference) applies live.
`)
	return err
}

// sectionDocs maps the path of every section of the tree to the doc tag of its field.
func sectionDocs() map[string]string {
	out := map[string]string{}
	var walk func(t reflect.Type, prefix string)
	walk = func(t reflect.Type, prefix string) {
		for i := range t.NumField() {
			f := t.Field(i)
			name, _, _ := strings.Cut(f.Tag.Get("json"), ",")
			if f.Type.Kind() != reflect.Struct || f.Type == secretType {
				continue
			}
			if f.Anonymous && name == "" { // an embedded struct adds its fields to this section
				walk(f.Type, prefix)
				continue
			}
			out[prefix+name] = f.Tag.Get("doc")
			walk(f.Type, prefix+name+".")
		}
	}
	walk(reflect.TypeFor[Tree](), "")
	return out
}

// WriteEnvMarkdown writes docs/configuration.md: every setting grouped by section, with its
// variable, type, default and description. It is generated, so that the page cannot drift from
// the code (`make generate`; a test and `make check` compare).
func WriteEnvMarkdown(w io.Writer) error {
	var b strings.Builder
	b.WriteString("<!-- Generated by `dash config env --markdown`; do not edit. Run `make generate`. -->\n\n")
	b.WriteString(`# Configuration reference

dash reads its settings from four layers; each overrides the one before it, setting by setting:
the built-in defaults, the settings saved from the UI, the config file and the environment. The
file is ` + "`DASH_CONFIG`" + `, or ` + "`config.yaml`" + ` in the data directory. The JSON Schema of the file is
` + "`dash config schema`" + `; ` + "`dash config validate`" + ` checks a file and the environment without starting dash.

Every setting has a variable: ` + "`DASH_`" + ` plus its path in UPPER_SNAKE case. Lists and objects are JSON
(` + "`DASH_PLUGINS_HARDWARE_HOSTS='[{\"nodename\":\"pve\"}]'`" + `). Append ` + "`_FILE`" + ` to read the value from a file
(` + "`DASH_PLUGINS_PROXMOX_TOKEN_SECRET_FILE=/run/secrets/pve`" + `); set only one of the two forms.

A secret takes a literal, ` + "`env:NAME`" + ` or ` + "`file:/path`" + `. A change to a ` + "`plugins.<id>`" + ` section applies live
for prometheus, alertmanager, gatus, victorialogs, proxmox, hardware, kubernetes, grafana, headlamp and launcher, except
for a setting marked "restart-only": that plugin restarts, and so do the plugins that use or require it
(a prometheus change restarts proxmox, hardware and kubernetes; a gatus change restarts hardware and
kubernetes; a proxmox change restarts hardware; a kubernetes change restarts proxmox; a grafana change
restarts alertmanager). A change to flux, or to any section that is not a plugin's, needs a restart. A rotated
secret file applies live.
`)
	docs := sectionDocs()
	// A section that holds both fields and sub-sections (plugins.kubernetes and its conventions)
	// is split in schema order; gather its rows under one heading, sections in first-seen order.
	var groups []string
	rows := map[string][]EnvVar{}
	for _, v := range EnvVars() {
		g := v.Path[:max(strings.LastIndex(v.Path, "."), 0)]
		if _, ok := rows[g]; !ok {
			groups = append(groups, g)
		}
		rows[g] = append(rows[g], v)
	}
	for _, g := range groups {
		title := "`" + g + "`"
		if g == "" {
			title = "Top level"
		}
		fmt.Fprintf(&b, "\n## %s\n\n", title)
		if d := docs[g]; d != "" {
			fmt.Fprintf(&b, "%s\n\n", d)
		}
		b.WriteString("| Setting | Variable | Type | Default | Description |\n|---|---|---|---|---|\n")
		for _, v := range rows[g] {
			def := "-"
			if v.Default != "" {
				def = "`" + v.Default + "`"
			}
			desc := v.Description
			if v.Secret {
				desc += " _Secret._"
			}
			if v.Restart {
				desc += " _Restart-only._"
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s |\n", v.Path, v.Name, v.Type, def, mdCell(desc))
		}
	}
	b.WriteString(`
## Process variables

These are not settings; the config file cannot set them.

| Variable | What |
|---|---|
| ` + "`DASH_CONFIG`" + ` | Path of the config file. It must exist. Without it dash reads ` + "`config.yaml`" + ` in the data directory when there is one. |
| ` + "`DASH_DEV`" + ` | ` + "`true`" + ` signs every request in as ` + "`dev`" + ` without authentication and uses the development defaults; it only starts on a loopback ` + "`server.listen`" + `. |
| ` + "`DASH_DEMO`" + ` | ` + "`true`" + ` serves fake data and contacts nothing; it opens no data directory. |
| ` + "`DASH_SECRET_KEY`" + `, ` + "`DASH_SECRET_KEY_FILE`" + ` | The key that encrypts secrets saved from the UI. Without one they can only be set through ` + "`env:`" + ` and ` + "`file:`" + ` references. |
| ` + "`DASH_SECRET_KEY_PREVIOUS`" + `, ` + "`DASH_SECRET_KEY_PREVIOUS_FILE`" + ` | The key being rotated out. |
| ` + "`KUBECONFIG`" + ` | Fills ` + "`plugins.kubernetes.kubeconfig`" + ` (another tool's variable: no ` + "`_FILE`" + ` form). The generated name wins over it. |

The names dash read before the config file (` + "`DASH_PUBLIC_URL`" + `, ` + "`DASH_VM_URL`" + ` and the like) were removed in
0.5.0; dash refuses to start and names the replacement. See "Removed variable names" in the README.
`)
	_, err := io.WriteString(w, b.String())
	return err
}

// mdCell makes s safe inside a table cell.
func mdCell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

func yesNo(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}
