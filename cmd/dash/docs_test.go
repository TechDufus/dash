// docs/plugins is what `dash docs plugins` writes, file for file: `make generate` rewrites it and
// `make check` diffs it, and this test fails first when only `go test` runs.
func TestPluginDocsAreCurrent(t *testing.T) {
	pages, err := pluginDocPages()
	if err != nil {
		t.Fatal(err)
	}
	dir := filepath.Join("..", "..", "docs", "plugins")
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	var have, want []string
	for _, e := range entries {
		have = append(have, e.Name())
	}
	for _, p := range pages {
		want = append(want, p.name)
		b, err := os.ReadFile(filepath.Join(dir, p.name))
		if err != nil {
			continue // reported by the file list below
		}
		if string(b) != p.text {
			t.Errorf("docs/plugins/%s is stale: run make generate", p.name)
		}
	}
	slices.Sort(want)
	if !slices.Equal(have, want) {
		t.Errorf("docs/plugins holds %v, want %v: run make generate", have, want)
	}
}

func TestPluginDocsCoverEveryPlugin(t *testing.T) {
	pages, err := pluginDocPages()
	if err != nil {
		t.Fatal(err)
	}
	text := map[string]string{}
	for _, p := range pages {
		text[p.name] = p.text
	}
	vars := config.EnvVars()
	for _, m := range builtinManifests() {
		page, ok := text[string(m.ID)+".md"]
		if !ok {
			t.Errorf("no page for %s", m.ID)
			continue
		}
		if !strings.HasPrefix(page, "<!-- Generated by `dash docs plugins`") {
			t.Errorf("%s: the page must say it is generated", m.ID)
		}
		for _, h := range []string{"# " + m.Name + "\n", "\n## What it shows\n", "\n## Settings\n", "\n## Actions\n", "\n## Demo twin\n"} {
			if !strings.Contains(page, h) {
				t.Errorf("%s: no %q", m.ID, strings.TrimSpace(h))
			}
		}
		for _, v := range vars {
			if strings.HasPrefix(v.Path, "plugins."+string(m.ID)+".") && !strings.Contains(page, "| `"+v.Path+"` | `"+v.Name+"` |") {
				t.Errorf("%s: no row for %s", m.ID, v.Path)
			}
		}
		for _, a := range m.Actions {
			if !strings.Contains(page, "`POST /api/v1/plugins/"+string(m.ID)+"/actions/"+a.Name+"`") {
				t.Errorf("%s: action %s is not documented", m.ID, a.Name)
			}
		}
		for _, n := range m.UI.Nav {
			if !strings.Contains(page, "| "+n.Title+" | `"+n.Path+"` |") {
				t.Errorf("%s: page %s is not listed", m.ID, n.Path)
			}
		}
		if hasRBAC := len(pluginRBAC[m.ID]) > 0; hasRBAC != strings.Contains(page, "\n## Kubernetes RBAC\n") {
			t.Errorf("%s: Kubernetes RBAC section present = %v, want %v", m.ID, !hasRBAC, hasRBAC)
		}
		if !strings.Contains(text["README.md"], "]("+string(m.ID)+".md)") {
			t.Errorf("the index does not link %s", m.ID)
		}
	}
}

// The tables the generator keeps beside the manifests name only shipped plugins and known slots.
func TestPluginDocTablesNameShippedPlugins(t *testing.T) {
	shipped := map[plugin.ID]bool{}
	for _, m := range builtinManifests() {
		shipped[m.ID] = true
	}
	for id, ps := range spaPanels {
		if !shipped[id] {
			t.Errorf("spaPanels names %s, which dash does not ship", id)
		}
		for _, p := range ps {
			if slotPages[p.slot] == "" {
				t.Errorf("%s/%s: slot %q has no page name", id, p.id, p.slot)
			}
		}
	}
	for id, gs := range pluginRBAC {
		if !shipped[id] {
			t.Errorf("pluginRBAC names %s, which dash does not ship", id)
		}
		for _, g := range gs {
			if g.when == "" || len(g.rules) == 0 {
				t.Errorf("%s: an RBAC group needs a condition and rules: %+v", id, g)
			}
		}
	}
}

// A hand-written section joins the generated one of the same heading; any other comes after the
// generated sections and before the demo twin, in the order written.
func TestPluginProseMergesBySection(t *testing.T) {
	var d docPlugin
	for _, f := range registry(nil) {
		if p := f(); p.Manifest().ID == "flux" {
			d = docPlugin{p, p.Manifest()}
		}
	}
	pr, err := parseProse("Intro text.\n\n## Upgrading\n\nExtra one.\n\n```sh\n## a shell comment, not a section\n```\n\n## Actions\n\nAction note.\n\n## Demo twin\n\nTwin note.\n")
	if err != nil {
		t.Fatal(err)
	}
	page, err := pluginPage(d, []docPlugin{d}, config.EnvVars(), pr)
	if err != nil {
		t.Fatal(err)
	}
	if len(pr.sections) != 3 || !strings.Contains(pr.sections[0].body, "## a shell comment") {
		t.Errorf("a heading inside a fenced block split the section: %+v", pr.sections)
	}
	order := []string{"Intro text.", "\n## What it shows\n", "\n## Actions\n", "Action note.", "\n## Kubernetes RBAC\n", "\n## Upgrading\n", "Extra one.", "\n## Demo twin\n", "Twin note."}
	at := 0
	for _, s := range order {
		i := strings.Index(page[at:], s)
		if i < 0 {
			t.Fatalf("%q missing or out of order in:\n%s", s, page)
		}
		at += i + len(s)
	}
	if strings.Count(page, "\n## Actions\n") != 1 || strings.Count(page, "\n## Demo twin\n") != 1 {
		t.Errorf("a merged section is repeated:\n%s", page)
	}
}

// A heading that only nearly names a generated section is a mistake, not a section of its own.
func TestPluginProseRefusesANearMissHeading(t *testing.T) {
	for _, h := range []string{"Setting", "settings", "Kubernetes rbac", "What it show", "Demo twins"} {
		if _, err := parseProse("Intro.\n\n## " + h + "\n\nText.\n"); err == nil {
			t.Errorf("## %s: no error", h)
		}
	}
	if _, err := parseProse("Intro.\n\n## Upgrading\n\nText.\n\n## Settings\n\nMore.\n"); err != nil {
		t.Errorf("exact and unrelated headings: %v", err)
	}
}

func TestDocsCommand(t *testing.T) {
	for _, args := range [][]string{{"docs"}, {"docs", "plugins"}, {"docs", "other", "x"}, {"docs", "plugins", "a", "b"}} {
		if err := command(args, &bytes.Buffer{}); err == nil || !strings.Contains(err.Error(), docsUsage) {
			t.Errorf("%v: error %v, want the usage", args, err)
		}
	}
	dir := t.TempDir()
	if err := command([]string{"docs", "plugins", dir}, &bytes.Buffer{}); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, "README.md")); err != nil {
		t.Error(err)
	}
	// It writes this repository's docs; an operator's usage text does not mention it.
	err := command([]string{"nope"}, &bytes.Buffer{})
	if err == nil || strings.Contains(err.Error(), "docs") {
		t.Errorf("unknown command error = %v, want one without the docs command", err)
	}
}
