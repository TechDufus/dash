// cleanEnv gives a test the environment of a plain production start and nothing else DASH_.
func cleanEnv(t *testing.T) {
	t.Helper()
	for _, kv := range os.Environ() {
		if k, _, _ := strings.Cut(kv, "="); strings.HasPrefix(k, "DASH_") || k == "KUBECONFIG" {
			t.Setenv(k, "")
		}
	}
	t.Setenv("DASH_DATA_DIR", t.TempDir())
	t.Setenv("DASH_SERVER_PUBLIC_URL", "https://dash.example.com")
}

func writeFile(t *testing.T, body string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "config.yaml")
	if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	return p
}

func validate(t *testing.T, args ...string) (string, error) {
	t.Helper()
	var out bytes.Buffer
	err := command(append([]string{"config", "validate"}, args...), &out)
	return out.String(), err
}

func TestConfigSchemaCommandPrintsTheSchema(t *testing.T) {
	var out bytes.Buffer
	if err := command([]string{"config", "schema"}, &out); err != nil {
		t.Fatal(err)
	}
	var doc map[string]any
	if err := json.Unmarshal(out.Bytes(), &doc); err != nil {
		t.Fatalf("not JSON: %v\n%s", err, out.String())
	}
	if doc["$schema"] != "https://json-schema.org/draft/2020-12/schema" || doc["type"] != "object" {
		t.Errorf("document header: %v", doc["$schema"])
	}
	if !strings.Contains(out.String(), "<prefix>_last_errors") {
		t.Error("descriptions must not be HTML-escaped")
	}
	if err := command([]string{"config", "schema", "extra"}, &out); err == nil {
		t.Error("an argument is a usage error")
	}
}

func TestConfigEnvMarkdownCommand(t *testing.T) {
	var out bytes.Buffer
	if err := command([]string{"config", "env", "--markdown"}, &out); err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"Generated by `dash config env --markdown`; do not edit", "`DASH_SERVER_PUBLIC_URL`", "## `plugins.proxmox`", "| Setting | Variable |"} {
		if !strings.Contains(out.String(), want) {
			t.Errorf("output lacks %q:\n%s", want, out.String())
		}
	}
	if err := command([]string{"config", "env", "--nope"}, &bytes.Buffer{}); err == nil || exitCode(err) != 2 {
		t.Errorf("an unknown flag is a usage error: %v", err)
	}
}

func TestValidateAcceptsAValidFileAndTheEnvironment(t *testing.T) {
	cleanEnv(t)
	p := writeFile(t, "plugins:\n  grafana: {url: 'https://grafana.example.com'}\n")
	out, err := validate(t, p)
	if err != nil || !strings.Contains(out, "configuration valid") || !strings.Contains(out, p) {
		t.Errorf("file: %v\n%s", err, out)
	}
	// With no argument it validates the environment and the default config file.
	out, err = validate(t)
	if err != nil || !strings.Contains(out, "no config file") {
		t.Errorf("environment: %v\n%s", err, out)
	}
}

func TestValidateReportsPathQualifiedErrorsAndExitsNonZero(t *testing.T) {
	cleanEnv(t)
	t.Setenv("DASH_PLUGINS_GRAFANA_URL", "ftp://grafana")
	p := writeFile(t, "plugins:\n  proxmox: {urll: 'https://pve.example.com', node: pve}\n  grafana: {url: 'https://grafana.example.com'}\nserver: {bogus: 1}\n")
	out, err := validate(t, p)
	if !errors.Is(err, errConfigInvalid) || exitCode(err) != 1 {
		t.Fatalf("err = %v (exit %d), want errConfigInvalid and exit 1", err, exitCode(err))
	}
	for _, want := range []string{
		"config file " + p + ": plugins.proxmox.urll: unknown field",
		"config file " + p + ": server.bogus: unknown field",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("output lacks %q:\n%s", want, out)
		}
	}
	// A value that parses but fails the checks names its layer too.
	cleanEnv(t)
	t.Setenv("DASH_PLUGINS_GRAFANA_URL", "ftp://grafana")
	out, err = validate(t)
	if !errors.Is(err, errConfigInvalid) || !strings.Contains(out, "plugins.grafana.url (env DASH_PLUGINS_GRAFANA_URL)") {
		t.Errorf("env problem: %v\n%s", err, out)
	}
	// A missing public URL is reported, once, with its remedy.
	cleanEnv(t)
	t.Setenv("DASH_SERVER_PUBLIC_URL", "")
	out, err = validate(t)
	if !errors.Is(err, errConfigInvalid) || !strings.Contains(out, "server.publicURL") || !strings.Contains(out, "1 problem\n") {
		t.Errorf("missing public URL: %v\n%s", err, out)
	}
	// A removed variable is a problem of the environment, not a crash.
	cleanEnv(t)
	t.Setenv("DASH_VM_URL", "http://prom.example.com")
	out, err = validate(t)
	if !errors.Is(err, errConfigInvalid) || !strings.Contains(out, "DASH_VM_URL -> DASH_PLUGINS_PROMETHEUS_URL") {
		t.Errorf("removed variable: %v\n%s", err, out)
	}
}

func TestValidateUsageErrorsExitTwo(t *testing.T) {
	cleanEnv(t)
	for _, args := range [][]string{{"--nope"}, {"a.yaml", "b.yaml"}, {filepath.Join(t.TempDir(), "missing.yaml")}} {
		if _, err := validate(t, args...); err == nil || errors.Is(err, errConfigInvalid) || exitCode(err) != 2 {
			t.Errorf("%v: err = %v (exit %d), want a usage error", args, err, exitCode(err))
		}
	}
}

// The references of secrets often point at files that exist only where dash runs: by default
// they count as set without being read; --resolve-secrets reads them.
func TestValidateSkipsSecretReadsByDefault(t *testing.T) {
	cleanEnv(t)
	missing := filepath.Join(t.TempDir(), "absent")
	p := writeFile(t, "plugins:\n  proxmox:\n    url: https://pve.example.com:8006\n    tokenID: dash@pve!ci\n    tokenSecret: file:"+missing+"\n")
	out, err := validate(t, p)
	if err != nil || !strings.Contains(out, "secret references were not read") {
		t.Fatalf("default: %v\n%s", err, out)
	}
	out, err = validate(t, p, "--resolve-secrets")
	if !errors.Is(err, errConfigInvalid) || !strings.Contains(out, "plugins.proxmox.tokenSecret") || !strings.Contains(out, "cannot read secret file") {
		t.Errorf("--resolve-secrets: %v\n%s", err, out)
	}
	out, err = validate(t, "--resolve-secrets", p)
	if !errors.Is(err, errConfigInvalid) {
		t.Errorf("the flag may come first: %v\n%s", err, out)
	}

	// An env: reference to a variable that is not set, and the _FILE form of the variable.
	env := writeFile(t, "plugins:\n  proxmox: {url: 'https://pve.example.com:8006', tokenID: 'u@pve!t', tokenSecret: 'env:DASH_TEST_NOT_SET'}\n")
	if out, err := validate(t, env); err != nil {
		t.Errorf("env: reference: %v\n%s", err, out)
	}
	t.Setenv("DASH_PLUGINS_PROXMOX_URL", "https://pve.example.com:8006")
	t.Setenv("DASH_PLUGINS_PROXMOX_TOKEN_ID", "u@pve!t")
	t.Setenv("DASH_PLUGINS_PROXMOX_TOKEN_SECRET_FILE", missing)
	if out, err := validate(t); err != nil {
		t.Errorf("_FILE variable: %v\n%s", err, out)
	}
	if out, err := validate(t, "--resolve-secrets"); !errors.Is(err, errConfigInvalid) || !strings.Contains(out, "plugins.proxmox.tokenSecret") {
		t.Errorf("_FILE variable with --resolve-secrets: %v\n%s", err, out)
	}

	// Skipping the read does not skip the checks: a token needs its URL and its ID.
	half := writeFile(t, "plugins:\n  proxmox: {tokenSecret: 'file:"+missing+"'}\n")
	cleanEnv(t)
	out, err = validate(t, half)
	if !errors.Is(err, errConfigInvalid) || !strings.Contains(out, "tokenID and tokenSecret must be set together") {
		t.Errorf("half a token: %v\n%s", err, out)
	}
}

// validate neither opens the data directory nor takes its lock, and never prints a secret.
func TestValidateTouchesNoStateAndLeaksNothing(t *testing.T) {
	cleanEnv(t)
	dir := filepath.Join(t.TempDir(), "data")
	t.Setenv("DASH_DATA_DIR", dir)
	const canary = "canary-literal-secret-9876"
	p := writeFile(t, "plugins:\n  proxmox: {url: 'https://pve.example.com:8006', tokenID: 'u@pve!t', tokenSecret: '"+canary+"'}\n")
	out, err := validate(t, p)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(out, canary) {
		t.Errorf("a secret was printed:\n%s", out)
	}
	if !strings.Contains(out, "warning:") || !strings.Contains(out, "plugins.proxmox.tokenSecret") {
		t.Errorf("a literal secret in the file is worth a warning:\n%s", out)
	}
	if _, err := os.Stat(dir); err == nil {
		t.Error("validate created the data directory")
	}
}

// validate runs the checks startup adds after resolving: a malformed secret key (never echoed)
// fails at once; a key file and the launcher file are read only with --resolve-secrets.
func TestValidateRunsTheStartupChecksAfterResolve(t *testing.T) {
	cleanEnv(t)
	t.Setenv("DASH_SECRET_KEY", "bad-but-secret-text")
	out, err := validate(t)
	if !errors.Is(err, errConfigInvalid) || !strings.Contains(out, "DASH_SECRET_KEY") {
		t.Errorf("bad key: %v\n%s", err, out)
	}
	if strings.Contains(out, "bad-but-secret-text") {
		t.Errorf("the key text was echoed:\n%s", out)
	}

	cleanEnv(t)
	t.Setenv("DASH_SECRET_KEY_PREVIOUS", strings.Repeat("A", 43)+"=")
	if out, err := validate(t); !errors.Is(err, errConfigInvalid) || !strings.Contains(out, "DASH_SECRET_KEY is not") {
		t.Errorf("previous key without a current one: %v\n%s", err, out)
	}

	cleanEnv(t)
	t.Setenv("DASH_SECRET_KEY_FILE", filepath.Join(t.TempDir(), "absent"))
	if out, err := validate(t); err != nil {
		t.Errorf("a key file is not read by default: %v\n%s", err, out)
	}
	if out, err := validate(t, "--resolve-secrets"); !errors.Is(err, errConfigInvalid) || !strings.Contains(out, "DASH_SECRET_KEY_FILE") {
		t.Errorf("key file with --resolve-secrets: %v\n%s", err, out)
	}

	cleanEnv(t)
	t.Setenv("DASH_PLUGINS_LAUNCHER_FILE", filepath.Join(t.TempDir(), "absent.yaml"))
	if out, err := validate(t); err != nil {
		t.Errorf("the launcher file is not read by default: %v\n%s", err, out)
	}
	if out, err := validate(t, "--resolve-secrets"); !errors.Is(err, errConfigInvalid) || !strings.Contains(out, "launcher file") {
		t.Errorf("launcher file with --resolve-secrets: %v\n%s", err, out)
	}
}

// validate prints the start's WARN about OAuth behind the identity proxy without
// server.directURL, and still exits zero.
func TestValidateWarnsProxyOAuthWithoutDirectURL(t *testing.T) {
	cleanEnv(t)
	t.Setenv("DASH_AUTH_MODE", "proxy")
	t.Setenv("DASH_AUTH_OAUTH_ENABLED", "true")
	out, err := validate(t)
	if err != nil || !strings.Contains(out, "warning:") || !strings.Contains(out, "server.directURL") || !strings.Contains(out, "routes.direct") {
		t.Errorf("proxy mode with OAuth and no direct URL: %v\n%s", err, out)
	}
	t.Setenv("DASH_SERVER_DIRECT_URL", "https://dash-direct.example.com")
	if out, err := validate(t); err != nil || strings.Contains(out, "routes.direct") {
		t.Errorf("with server.directURL: %v\n%s", err, out)
	}
}
